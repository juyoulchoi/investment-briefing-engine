CREATE VIEW tb_hold AS
SELECT a."ACCT_TP" AS market_scope, s."STK_CD" AS stock_code,
       s."STK_NM" AS stock_name, s."LIST_SCOPE" AS listing_scope,
       s."ASSET_TP" AS asset_type, s."EXCH_NM" AS exchange_name,
       s."CURR" AS currency, s."PRVDR" AS provider, s."ACTV_YN" AS active_yn,
       a."REG_DT" AS created_at, a."MOD_DT" AS updated_at,
       a."QTY" AS qty, a."AVG_PRC" AS avg_prc
FROM "TB_ACCT_STK" a
JOIN "TB_STK" s ON s."MKT_CD" = a."MKT_CD" AND s."STK_CD" = a."STK_CD";

