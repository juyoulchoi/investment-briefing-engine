CREATE TABLE "TB_STK" (
    "MKT_CD"      VARCHAR(10)  NOT NULL,
    "STK_CD"      VARCHAR(30)  NOT NULL,
    "STK_NM"      VARCHAR(100) NOT NULL,
    "LIST_SCOPE"  VARCHAR(20)  NOT NULL,
    "ASSET_TP"    VARCHAR(30),
    "EXCH_NM"     VARCHAR(50),
    "CURR"        VARCHAR(10),
    "PRVDR"       VARCHAR(30),
    "ACTV_YN"     CHAR(1)      NOT NULL DEFAULT 'Y',
    "REG_DT"      TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "MOD_DT"      TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT "PK_STK" PRIMARY KEY ("MKT_CD", "STK_CD"),
    CONSTRAINT "CK_STK_01" CHECK ("MKT_CD" IN ('KO', 'US')),
    CONSTRAINT "CK_STK_02" CHECK ("LIST_SCOPE" IN ('DOMESTIC', 'OVERSEAS')),
    CONSTRAINT "CK_STK_03" CHECK ("ACTV_YN" IN ('Y', 'N'))
);

INSERT INTO "TB_STK"
    ("MKT_CD", "STK_CD", "STK_NM", "LIST_SCOPE", "ASSET_TP",
     "EXCH_NM", "CURR", "PRVDR", "ACTV_YN", "REG_DT", "MOD_DT")
SELECT
    CASE WHEN "LIST_SCOPE" = 'DOMESTIC' THEN 'KO' ELSE 'US' END,
    "STK_CD", MAX("STK_NM"), "LIST_SCOPE", MAX("ASSET_TP"),
    MAX("EXCH_NM"), MAX("CURR"), MAX("PRVDR"), MAX("ACTV_YN"),
    MIN("REG_DT"), MAX("MOD_DT")
FROM "TB_HOLD"
GROUP BY "LIST_SCOPE", "STK_CD";

CREATE TABLE "TB_ACCT_STK" (
    "ACCT_TP"  VARCHAR(20) NOT NULL,
    "MKT_CD"   VARCHAR(10) NOT NULL,
    "STK_CD"   VARCHAR(30) NOT NULL,
    "QTY"      NUMERIC(18, 6),
    "AVG_PRC"  NUMERIC(18, 4),
    "REG_DT"   TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "MOD_DT"   TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT "PK_ACCT_STK" PRIMARY KEY ("ACCT_TP", "MKT_CD", "STK_CD"),
    CONSTRAINT "FK_ACCT_STK_01" FOREIGN KEY ("ACCT_TP")
        REFERENCES "TB_ACCT" ("ACCT_TP"),
    CONSTRAINT "FK_ACCT_STK_02" FOREIGN KEY ("MKT_CD", "STK_CD")
        REFERENCES "TB_STK" ("MKT_CD", "STK_CD") ON DELETE CASCADE
);

INSERT INTO "TB_ACCT_STK"
    ("ACCT_TP", "MKT_CD", "STK_CD", "QTY", "AVG_PRC", "REG_DT", "MOD_DT")
SELECT "MKT_SCOPE",
