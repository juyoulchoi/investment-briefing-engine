INSERT INTO "TB_STK_PRC"
    ("MKT_CD", "STK_CD", "TRD_DT", "OPEN_PRC", "HIGH_PRC", "LOW_PRC",
     "CLS_PRC", "ADJ_CLS", "VOL", "PRVDR")
SELECT DISTINCT ON (r."BASE_DT", r."PAYLOAD"->>'ISU_CD')
    'KO', r."PAYLOAD"->>'ISU_CD', r."BASE_DT",
    NULLIF(replace(r."PAYLOAD"->>'TDD_OPNPRC', ',', ''), '')::numeric,
    NULLIF(replace(r."PAYLOAD"->>'TDD_HGPRC', ',', ''), '')::numeric,
    NULLIF(replace(r."PAYLOAD"->>'TDD_LWPRC', ',', ''), '')::numeric,
    NULLIF(replace(r."PAYLOAD"->>'TDD_CLSPRC', ',', ''), '')::numeric,
    NULLIF(replace(r."PAYLOAD"->>'TDD_CLSPRC', ',', ''), '')::numeric,
    COALESCE(NULLIF(replace(r."PAYLOAD"->>'ACC_TRDVOL', ',', ''), '')::bigint, 0),
    'KRX'
FROM "TB_KRX_DATA_ROW" r
JOIN "TB_STK" s
  ON s."MKT_CD" = 'KO' AND s."STK_CD" = r."PAYLOAD"->>'ISU_CD'
WHERE r."DATA_CD" IN ('KOSPI_STOCK_DAILY', 'KOSDAQ_STOCK_DAILY', 'ETF_DAILY')
  AND r."BASE_DT" BETWEEN DATE '2026-07-01' AND DATE '2026-07-28'
  AND NULLIF(r."PAYLOAD"->>'TDD_CLSPRC', '') IS NOT NULL
ON CONFLICT ("MKT_CD", "STK_CD", "TRD_DT") DO NOTHING;

CREATE VIEW tb_stk_prc AS
SELECT "ID" AS id, "STK_CD" AS symbol, "TRD_DT" AS trading_day,
       "OPEN_PRC" AS open_price, "HIGH_PRC" AS high_price, "LOW_PRC" AS low_price,
       "CLS_PRC" AS close_price, "ADJ_CLS" AS adjusted_close, "VOL" AS volume,
       "PRVDR" AS provider, "REG_DT" AS created_at, "MOD_DT" AS updated_at,
       CASE WHEN "MKT_CD" = 'US' THEN 'GENERAL' ELSE 'DOMESTIC' END AS market_scope
FROM "TB_STK_PRC";

