CREATE TABLE "TB_KOFIA_BUSINESS_REF" (
  "MARKET_TYP_CD" CHAR(1) NOT NULL,
  "LARGE_CATEGORY_CD" VARCHAR(30) NOT NULL,
  "MIDDLE_CATEGORY_CD" VARCHAR(30) NOT NULL,
  "SMALL_CATEGORY_CD" VARCHAR(30) NOT NULL,
  "BUSINESS_SHORT_CD" VARCHAR(30) NOT NULL,
  "BUSINESS_NM" VARCHAR(300) NOT NULL,
  "SORT_SEQ" INTEGER,
  "PAYLOAD" JSONB NOT NULL,
  "RAW_HASH" VARCHAR(64) NOT NULL,
  "USE_YN" CHAR(1) NOT NULL DEFAULT 'Y',
  "FIRST_COLLECT_DTTM" TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  "LAST_COLLECT_DTTM" TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  "CRT_DTTM" TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  "UPD_DTTM" TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY("MARKET_TYP_CD", "LARGE_CATEGORY_CD", "MIDDLE_CATEGORY_CD",
    "SMALL_CATEGORY_CD", "BUSINESS_SHORT_CD"),
  CONSTRAINT "CK_KOFIA_BUSINESS_REF_01" CHECK ("MARKET_TYP_CD" IN ('1', '2')),
  CONSTRAINT "CK_KOFIA_BUSINESS_REF_02" CHECK ("USE_YN" IN ('Y', 'N'))
