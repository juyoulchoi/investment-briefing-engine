CREATE TABLE "TB_KOFIA_COMPANY_REF" (
  "TABLE_NM" VARCHAR(100) NOT NULL,
  "COMPANY_TYP_CD" CHAR(1) NOT NULL,
  "COMPANY_CD" VARCHAR(60) NOT NULL,
  "COMPANY_NM" VARCHAR(300) NOT NULL,
  "MIDDLE_CATEGORY_CD" VARCHAR(60),
  "PAYLOAD" JSONB NOT NULL,
  "RAW_HASH" VARCHAR(64) NOT NULL,
  "USE_YN" CHAR(1) NOT NULL DEFAULT 'Y',
  "FIRST_COLLECT_DTTM" TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  "LAST_COLLECT_DTTM" TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  "CRT_DTTM" TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  "UPD_DTTM" TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY("TABLE_NM", "COMPANY_TYP_CD", "COMPANY_CD"),
  CONSTRAINT "CK_KOFIA_COMPANY_REF_01" CHECK ("COMPANY_TYP_CD" IN ('1', '2')),
  CONSTRAINT "CK_KOFIA_COMPANY_REF_02" CHECK ("USE_YN" IN ('Y', 'N'))
);

