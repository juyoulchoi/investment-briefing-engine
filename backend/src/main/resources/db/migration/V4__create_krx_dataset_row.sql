CREATE TABLE IF NOT EXISTS TB_KRX_DATASET_ROW (
 id BIGSERIAL PRIMARY KEY,
 dataset_code VARCHAR(50) NOT NULL,
 base_date DATE NOT NULL,
 row_key VARCHAR(500) NOT NULL,
 payload JSONB NOT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT UK_KRX_DATASET_ROW UNIQUE(dataset_code, base_date, row_key)
);
CREATE INDEX IF NOT EXISTS IX_KRX_DATASET_DATE ON TB_KRX_DATASET_ROW(dataset_code, base_date DESC);
COMMENT ON TABLE TB_KRX_DATASET_ROW IS 'KRX OpenAPI 데이터셋별 원문 행';
COMMENT ON COLUMN TB_KRX_DATASET_ROW.dataset_code IS '수집 데이터셋 코드';
COMMENT ON COLUMN TB_KRX_DATASET_ROW.base_date IS '기준일자';
COMMENT ON COLUMN TB_KRX_DATASET_ROW.row_key IS '데이터셋 내 행 고유키';
COMMENT ON COLUMN TB_KRX_DATASET_ROW.payload IS 'KRX 응답 원문 JSON';
