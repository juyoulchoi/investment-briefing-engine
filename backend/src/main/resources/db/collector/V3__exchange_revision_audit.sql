CREATE TABLE "TB_EXCH_SOURCE_REVISION" (
 "REVISION_ID" BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
 "BASE_DT" DATE NOT NULL, "BASE_CURR_CD" VARCHAR(10) NOT NULL, "QUOTE_CURR_CD" VARCHAR(10) NOT NULL,
 "OLD_RATE" NUMERIC(20,6) NOT NULL, "NEW_RATE" NUMERIC(20,6) NOT NULL,
 "OLD_COLLECT_DTTM" TIMESTAMPTZ NOT NULL, "REVISED_DTTM" TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 "DATA_SRC_CD" VARCHAR(30) NOT NULL
);
CREATE FUNCTION exchange_source_revision() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF OLD."EXCH_RT" IS DISTINCT FROM NEW."EXCH_RT" THEN
  INSERT INTO "TB_EXCH_SOURCE_REVISION"("BASE_DT","BASE_CURR_CD","QUOTE_CURR_CD","OLD_RATE","NEW_RATE","OLD_COLLECT_DTTM","DATA_SRC_CD")
  VALUES(OLD."BASE_DT",OLD."BASE_CURR_CD",OLD."QUOTE_CURR_CD",OLD."EXCH_RT",NEW."EXCH_RT",OLD."COLLECT_DTTM",NEW."DATA_SRC_CD");
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER exchange_source_revision_audit BEFORE UPDATE ON "TB_EXCH_DAY"
FOR EACH ROW EXECUTE FUNCTION exchange_source_revision();
