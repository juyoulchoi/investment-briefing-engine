CREATE TABLE "TB_EXCH_DAY"(
 "BASE_DT" DATE NOT NULL, "BASE_CURR_CD" VARCHAR(10) NOT NULL,
 "QUOTE_CURR_CD" VARCHAR(10) NOT NULL, "EXCH_RT" NUMERIC(20,6) NOT NULL,
 "PREV_EXCH_RT" NUMERIC(20,6), "CHG_AMT" NUMERIC(20,6), "CHG_RT" NUMERIC(10,4),
 "HIGH_52W_RT" NUMERIC(20,6), "LOW_52W_RT" NUMERIC(20,6), "PRESS_SCR" NUMERIC(10,4),
 "DATA_SRC_CD" VARCHAR(30) NOT NULL, "DATA_STS" VARCHAR(20) NOT NULL DEFAULT 'FRESH',
 "COLLECT_DTTM" TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 PRIMARY KEY("BASE_DT","BASE_CURR_CD","QUOTE_CURR_CD"), CHECK("EXCH_RT">0),
 CHECK("DATA_STS" IN ('FRESH','STALE','MISSING','PARTIAL','ERROR'))
);
CREATE INDEX "IDX_SOURCE_EXCH_PAIR_DATE" ON "TB_EXCH_DAY"("BASE_CURR_CD","QUOTE_CURR_CD","BASE_DT" DESC);
